#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
[LJack Game Protocol v1.8.0] Commercial Game Release Doctor & Health Auditor
============================================================================
Performs exhaustive AST & static inspection of the game project against
Steam/Commercial Store release standards:
  1. Atomic Save Data & Immediate Economic Commit Flush
  2. Production Debug Seal (F1 Live Tuner disabled in release)
  3. Display, Resolution & Reduced-Motion Adaptability
  4. Audio Safety & Polyphony Rig (Dummy fallback, 3-bus volume, gesture guard)
  5. Multi-language Localization (i18n >= 2 languages)
  6. UX Copy Gate Integrity (Zero developer/harness jargon in player UI)
  7. Artifact cleanliness, Stub/TODO audit & Asset Manifest realization
"""

import os
import sys
import fnmatch
import json
import re
import argparse

if sys.stdout.encoding != 'utf-8':
    try:
        sys.stdout.reconfigure(encoding='utf-8')
    except Exception:
        pass

IGNORED_DIRS = {'.git', '__pycache__', 'node_modules', 'dist', 'dist_web', '.godot', '_internal'}
SCANNABLE_EXTS = {'.py', '.js', '.ts', '.gd', '.json', '.html', '.css', '.rs'}

PROHIBITED_UX_TERMS = {
    "하네스", "harness", "인터록", "interlock", "fsm", "자가 치유", "self-healing",
    "ljack", "히트박스", "hitbox", "서브스텝", "substep", "코요테 타임", "coyote time",
    "임시 수정", "temp fix", "버그 수정", "ai 생성", "generated by ai"
}

STUB_MARKER_RX = re.compile(
    r'\b(?:TODO|FIXME|XXX|NotImplementedError)\b|throw\s+new\s+Error\s*\(\s*["\'][^"\']*not\s+implemented',
    re.IGNORECASE,
)


class GameReleaseDoctor:
    def __init__(self, target_dir: str, strict: bool = False, phase: int = 2):
        self.target_dir = os.path.abspath(target_dir)
        self.strict = strict
        self.phase = phase
        
        # Audit Flags
        self.has_atomic_save = False
        self.has_web_persistence = False
        self.has_production_seal = False
        self.has_tauri_config = os.path.isfile(os.path.join(self.target_dir, "src-tauri", "tauri.conf.json"))
        self.has_debug_tuner = False
        self.has_fullscreen_toggle = False
        self.has_audio_mixer = False
        self.has_audio_safety_guard = False
        self.has_localization = False
        self.ux_copy_violations = []
        self.junk_files = []
        self.stub_hits = []
        self.manifest_total_assets = 0
        self.manifest_missing_assets = []
        self.total_source_files = 0
        self.has_keyframes_anim = False
        self.has_reduced_motion = False
        self.has_exit_save_flush = False
        self.advisories = []

    def inspect_workspace(self):
        # 1. Check locales directory & audit dictionary UX copy
        locales_dir = os.path.join(self.target_dir, "locales")
        if os.path.isdir(locales_dir):
            loc_files = [f for f in os.listdir(locales_dir) if f.endswith((".json", ".cfg", ".po"))]
            if len(loc_files) >= 2:
                self.has_localization = True

            for lf in loc_files:
                if lf.endswith(".json"):
                    try:
                        with open(os.path.join(locales_dir, lf), "r", encoding="utf-8", errors="ignore") as jfp:
                            data = json.load(jfp)
                        if isinstance(data, dict):
                            for k, v in data.items():
                                if isinstance(v, str):
                                    v_low = v.lower()
                                    for term in PROHIBITED_UX_TERMS:
                                        if term in v_low:
                                            self.ux_copy_violations.append(f"locales/{lf} [{k}] contains '{term}'")
                    except Exception:
                        pass

        for root, dirs, files in os.walk(self.target_dir):
            dirs[:] = [d for d in dirs if d not in IGNORED_DIRS]
            for f in files:
                fpath = os.path.join(root, f)
                lower_f = f.lower()

                # Junk file detection
                for pat in ["test_*.log", "*.tmp", "*.bak", "crash.dmp"]:
                    if fnmatch.fnmatch(lower_f, pat):
                        self.junk_files.append(fpath)

                ext = os.path.splitext(f)[1].lower()
                if ext in SCANNABLE_EXTS:
                    self.total_source_files += 1
                    try:
                        with open(fpath, "r", encoding="utf-8", errors="ignore") as fp:
                            content = fp.read()

                        # Check Atomic / Client Save
                        if any(term in content for term in ["os.replace", "NamedTemporaryFile", "ConfigFile.save", "atomic_save"]):
                            self.has_atomic_save = True
                        if any(term in content for term in ["localStorage.setItem", "indexedDB", "__TAURI__", "saveRunNow"]):
                            self.has_web_persistence = True

                        # Check Production Debug Seal & Live Tuner presence
                        if any(term in content for term in ["PRODUCTION_BUILD", "DEBUG_TUNER", "is_debug", "OS.is_debug_build()"]):
                            self.has_production_seal = True
                        if any(term in content for term in ["tuner_overlay", "live-tuner", "F1_TUNER", "DEBUG_TUNER"]):
                            self.has_debug_tuner = True

                        # Check Fullscreen / Resolution Toggle
                        if any(term in content for term in ["FULLSCREEN", "set_fullscreen", "window/size/mode", "toggle_fullscreen"]):
                            self.has_fullscreen_toggle = True

                        # Check Audio Mixer / Volume control
                        if any(term in content for term in ["mixer", "volume", "sound", "AudioServer", "AudioContext"]):
                            self.has_audio_mixer = True

                        # Check Audio Fallback / Safety Guard
                        if any(term in content for term in ["SDL_AUDIODRIVER", "dummy", "resume()", "linear_to_db", "set_num_channels", "fadeout"]):
                            self.has_audio_safety_guard = True

                        # Check exit save flush & CSS reduced motion
                        if any(term in content for term in ["beforeunload", "pagehide", "atexit", "saveRunNow", "flushSave"]):
                            self.has_exit_save_flush = True
                        if "@keyframes" in content:
                            self.has_keyframes_anim = True
                        if "prefers-reduced-motion" in content:
                            self.has_reduced_motion = True

                        # Fast UX check & stub marker scan (skip meta docs)
                        if not any(k in fpath.lower() for k in ["skill.md", "reference", "script", "readme.md"]):
                            for line_no, line in enumerate(content.splitlines(), start=1):
                                line_s = line.strip()
                                if ext != ".json" and STUB_MARKER_RX.search(line):
                                    rel_p = os.path.relpath(fpath, self.target_dir)
                                    self.stub_hits.append(f"{rel_p}:{line_no} -> {line_s[:80]}")
                                if any(fn in line_s for fn in ["draw_text", "fillText", "setText", "setWindowTitle", "render("]):
                                    line_low = line_s.lower()
                                    for term in PROHIBITED_UX_TERMS:
                                        if term in line_low:
                                            self.ux_copy_violations.append(f"{os.path.basename(fpath)}: contains '{term}'")

                    except Exception:
                        pass

        # Inspect asset_manifest.json realization (files on disk vs fallback-only entries)
        for rel_manifest in (os.path.join("specs", "asset_manifest.json"), os.path.join("assets", "asset_manifest.json")):
            manifest_path = os.path.join(self.target_dir, rel_manifest)
            if os.path.isfile(manifest_path):
                try:
                    with open(manifest_path, "r", encoding="utf-8-sig") as mfp:
                        mdata = json.load(mfp)
                    assets = mdata.get("assets", {})
                    if isinstance(assets, dict):
                        for aid, entry in assets.items():
                            if not isinstance(entry, dict):
                                continue
                            self.manifest_total_assets += 1
                            apath = entry.get("path", "")
                            if apath:
                                resolved = os.path.join(self.target_dir, apath)
                                public_resolved = os.path.join(self.target_dir, "public", apath)
                                if not (os.path.isfile(resolved) or os.path.isfile(public_resolved)):
                                    self.manifest_missing_assets.append(f"{aid} -> {apath}")
                except Exception:
                    pass
                break

    def run_checkup(self) -> int:
        print("=" * 65)
        print(" [LJack Game Protocol] Commercial Game Release Doctor")
        print("=" * 65)
        print(f"[*] Target Directory: {self.target_dir}")

        self.inspect_workspace()

        score = 0
        checks = []
        action_items = []

        # 1. Atomic / Persistent Save Data Rig (20 pts)
        if self.has_atomic_save:
            score += 20
            checks.append(("[PASS]", "Pillar 7: Atomic Save Rig (Crash-proof os.replace/Temp save active) (+20)"))
        elif self.has_web_persistence and self.has_exit_save_flush:
            score += 20
            checks.append(("[PASS]", "Pillar 7: Client/Tauri Save Rig + Exit Flush Guard active (+20)"))
        elif self.has_web_persistence:
            score += 12
            checks.append(("[WARN]", "Pillar 7: Web/Tauri persistence found but missing explicit exit-flush guard (+12)"))
            action_items.append("Add synchronous flush on `beforeunload`/`pagehide` and economic/random commits.")
        else:
            checks.append(("[WARN]", "Pillar 7: Missing Save Integrity Rig (Risk of save file corruption/loss) (+0)"))
            action_items.append("Wrap save routine with os.replace() / temporary write or sync flush commit guards.")

        # 2. Production Debug Seal (15 pts)
        if self.has_production_seal:
            score += 15
            checks.append(("[PASS]", "Pillar 5 & 8: Production Debug Seal (F1 Tuner sealed for commercial build) (+15)"))
        elif self.has_tauri_config and not self.has_debug_tuner:
            score += 15
            checks.append(("[PASS]", "Pillar 5 & 8: Tauri release config verified (no unsealed live F1 tuner exposed) (+15)"))
        else:
            checks.append(("[WARN]", "Pillar 5 & 8: No PRODUCTION_BUILD flag found (F1 Tuner may be exposed to players) (+0)"))
            action_items.append("Add PRODUCTION_BUILD boolean flag to disable [F1] Tuner overlay in commercial releases.")

        # 3. Display & Resolution Adaptability (10 pts)
        if self.has_fullscreen_toggle:
            score += 10
            checks.append(("[PASS]", "Display: Fullscreen / Resolution adaptability supported (+10)"))
        else:
            checks.append(("[WARN]", "Display: Missing Fullscreen / Windowed toggle option (+0)"))
            action_items.append("Add Fullscreen toggle (e.g. Alt+Enter or F11) for Steam Deck / Wide display compliance.")

        # 4. Pillar 10: Audio Safety & Polyphony Rig (15 pts)
        if self.has_audio_mixer and self.has_audio_safety_guard:
            score += 15
            checks.append(("[PASS]", "Pillar 10: Audio Safety & Polyphony Rig (Mixer + Dummy/Safety Guard active) (+15)"))
        elif self.has_audio_mixer:
            score += 8
            checks.append(("[WARN]", "Pillar 10: Audio mixer found but missing headless dummy fallback / gesture guard (+8)"))
            action_items.append("Refer to references/audio_runtime_harness_guide.md to add dummy audio fallback or resume guards.")
        else:
            checks.append(("[WARN]", "Pillar 10: No audio mixer or master/BGM/SFX volume control found (+0)"))
            action_items.append("Implement independent volume channels (Master/BGM/SFX) and dummy driver fallback.")

        # 5. Commercial Localization i18n (15 pts)
        if self.has_localization:
            score += 15
            checks.append(("[PASS]", "Pillar 8: Commercial Localization (locales/ with >= 2 languages) verified (+15)"))
        else:
            checks.append(("[WARN]", "Pillar 8: Missing locales/ directory or multi-language dictionaries (+0)"))
            action_items.append("Run 'python scripts/localization_linter.py <dir> --rewrite' to extract dictionaries and auto-replace hardcoded literals with t('KEY').")

        # 6. UX Copy Gate Integrity (10 pts)
        if not self.ux_copy_violations:
            score += 10
            checks.append(("[PASS]", "UX Copy Gate: 0 developer/harness jargon violations in player UI (+10)"))
        else:
            checks.append(("[WARN]", f"UX Copy Gate: Found {len(self.ux_copy_violations)} developer jargon term(s) in player UI (+0)"))
            action_items.append("Run python scripts/localization_linter.py to sanitize developer jargon from player UI strings.")

        # 7. Artifact Cleanliness (15 pts)
        if not self.junk_files:
            score += 15
            checks.append(("[PASS]", "Pillar 8: Clean Release Artifacts (0 test logs / temporary dumps) (+15)"))
        else:
            checks.append(("[FAIL]", f"Pillar 8: Found {len(self.junk_files)} temporary log/test dumps in release directory! (+0)"))
            action_items.append(f"Wipe {len(self.junk_files)} transient log files before uploading to Steam / Stove.")

        if self.stub_hits:
            checks.append(("[FAIL]", f"Anti-Stub Gate: Found {len(self.stub_hits)} unfinished TODO/FIXME/NotImplemented stub(s)!"))
            action_items.append(
                f"Resolve all {len(self.stub_hits)} stub marker(s) before declaring milestone/release complete (first: {self.stub_hits[0]})."
            )
        else:
            checks.append(("[PASS]", "Anti-Stub Gate: 0 unfinished TODO/FIXME/NotImplemented markers in source."))

        if self.manifest_total_assets > 0:
            missing_cnt = len(self.manifest_missing_assets)
            if missing_cnt == 0:
                checks.append(("[PASS]", f"Asset Realization: All {self.manifest_total_assets} manifest asset(s) exist on disk."))
            elif missing_cnt == self.manifest_total_assets:
                checks.append(("[WARN]", f"Asset Realization: 0/{self.manifest_total_assets} manifest files exist on disk (verify real SVG/procedural visuals & WebAudio SFX are active, not debug checkerboards)."))
                self.advisories.append(
                    f"All {self.manifest_total_assets} registered asset_manifest entries lack files on disk; ensure SVG/procedural art & SFX are implemented rather than checkerboard fallbacks."
                )
            else:
                checks.append(("[INFO]", f"Asset Realization: {self.manifest_total_assets - missing_cnt}/{self.manifest_total_assets} manifest files on disk ({missing_cnt} fallback/pending)."))

        # Print Checks
        for status, msg in checks:
            print(f" {status} {msg}")

        print("-" * 65)
        if self.phase == 1:
            action_items = [
                item for item in action_items
                if "stub marker" in item or "transient log" in item
            ]
            print(f"[*] Phase 1 Core Hygiene Check (Release Score: {score} / 100, Release QA deferred to Phase 2)")
            if self.stub_hits or self.junk_files:
                print("[PHASE 1 BLOCKED] Resolve unfinished stubs/TODOs and temp logs before advancing milestone.")
            else:
                print("[PHASE 1 CLEAN] Zero code stubs detected; proceed with gameplay & visual/E2E verification.")
        else:
            print(f"[*] Commercial Readiness Score: {score} / 100")

            if score >= 80 and not self.stub_hits:
                print("[COMMERCIAL GRADE APPROVED] Ready for Steam / Stove / Itch.io publishing.")
            else:
                print("[NEEDS REFINEMENT] Project requires commercial polish before public release.")

        if self.has_keyframes_anim and not self.has_reduced_motion:
            self.advisories.append("CSS @keyframes animation found without `@media (prefers-reduced-motion: reduce)` fallback.")
        if (self.has_atomic_save or self.has_web_persistence) and not self.has_exit_save_flush:
            self.advisories.append("Save system lacks explicit exit-flush guard (`beforeunload`/`pagehide`/`atexit` or sync commit helper).")

        for candidate in [
            os.path.join(self.target_dir, "src-tauri", "icons", "icon.png"),
            os.path.join(self.target_dir, "assets", "ui", "app_icon.png"),
        ]:
            if os.path.isfile(candidate):
                try:
                    from PIL import Image
                    with Image.open(candidate) as im:
                        rgba = im.convert("RGBA")
                        w, h = rgba.size
                        alpha_band = rgba.getchannel("A").point(lambda a: 255 if a > 20 else 0)
                        bbox = alpha_band.getbbox()
                        if not bbox or (bbox[2] - bbox[0]) / w < 0.92 or (bbox[3] - bbox[1]) / h < 0.92:
                            pct_w = 0.0 if not bbox else ((bbox[2] - bbox[0]) / w) * 100
                            pct_h = 0.0 if not bbox else ((bbox[3] - bbox[1]) / h) * 100
                            self.advisories.append(
                                f"Desktop icon {os.path.relpath(candidate, self.target_dir)} ({w}x{h}) covers only {pct_w:.1f}%x{pct_h:.1f}% (<92% full-bleed)."
                            )
                except Exception:
                    pass

        # Staging leakage & stale archive advisories
        dist_web_assets = os.path.join(self.target_dir, "dist-web", "assets")
        if os.path.isdir(dist_web_assets):
            for leak_dir in ("_raw_cache", "style_samples", "workflows", "temp"):
                if os.path.isdir(os.path.join(dist_web_assets, leak_dir)):
                    self.advisories.append(f"Staging bundle dist-web/assets/{leak_dir} should be excluded before release build.")

        dist_dir = os.path.join(self.target_dir, "dist")
        if os.path.isdir(dist_dir):
            exes = [os.path.join(dist_dir, f) for f in os.listdir(dist_dir) if f.lower().endswith(".exe")]
            zips = [os.path.join(dist_dir, f) for f in os.listdir(dist_dir) if f.lower().endswith(".zip")]
            if exes and zips:
                newest_exe = max(os.path.getmtime(p) for p in exes)
                for zp in zips:
                    if os.path.getmtime(zp) + 300 < newest_exe:
                        self.advisories.append(f"Stale release archive {os.path.relpath(zp, self.target_dir)} is older than latest .exe build.")

        if action_items:
            print("\n[🎯 ACTION ITEMS (Commercial Polish Directive)]:")
            for idx, item in enumerate(action_items, 1):
                print(f"  {idx}. {item}")

        if self.advisories:
            print("\n[🔭 RELEASE ADVISORIES (Visual / Save / Motion)]:")
            for adv in self.advisories:
                print(f"  - {adv}")

        if self.stub_hits:
            print("\n[⛔ UNFINISHED STUBS DETECTED]:")
            for hit in self.stub_hits[:10]:
                print(f"  - {hit}")
            if len(self.stub_hits) > 10:
                print(f"  ... and {len(self.stub_hits) - 10} more.")

        print("=" * 65)
        if self.phase == 1:
            return 1 if (self.stub_hits or self.junk_files) else 0
        if score < 70 or (self.strict and (score < 100 or bool(self.stub_hits))):
            return 1
        return 0

def main():
    parser = argparse.ArgumentParser(description="LJack Commercial Game Release Doctor")
    parser.add_argument("game_dir", nargs="?", default=".", help="Target game directory")
    parser.add_argument("--strict", action="store_true", help="Fail if score is less than 100 or stubs remain")
    parser.add_argument("--phase", type=int, choices=[1, 2], default=2, help="Audit phase: 1=core anti-stub hygiene, 2=full commercial release")
    args = parser.parse_args()

    doctor = GameReleaseDoctor(args.game_dir, args.strict, args.phase)
    return doctor.run_checkup()

if __name__ == "__main__":
    sys.exit(main())
